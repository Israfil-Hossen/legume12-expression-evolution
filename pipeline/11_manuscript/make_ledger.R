add <- function(key, value, source, note = "", digits = 3) {
  raw <- value
  if (is.numeric(value) && !is.integer(value) && value != 0 && abs(value) < 0.5 * 10^-digits) digits <- -floor(log10(abs(value)))   # never print a nonzero value as 0.000
  shown <- if (is.numeric(value) && !is.integer(value) && value != round(value)) formatC(value, format = "f", digits = digits) else as.character(value)
  if (is.numeric(value) && grepl("rho|_est|_lo$|_hi$|delta|_r[DNP]_|S5_1[BC]_.*median", key) && !grepl("1A_F_|2A_E_", key) && !is.integer(value) && value > 0 && value < 1e3)
    shown <- sub("^([0-9])", "+\\1", shown)
  L[[length(L) + 1]] <<- data.table(id = key, value = shown, raw = as.character(raw), source = source, note = note)
}
